def text(s, x0, y0, px, col, bg=None):
    w = len(s) * 6 * px
    if bg is not None:
        p.fb_fill(x0, y0, w, 8 * px, bg)
    for i, ch in enumerate(s):
        g = F5.get(ch, F5[' '])
        for k, b in enumerate(g):
            if b == '1':
                p.fb_fill(x0 + (i * 6 + k % 5) * px, y0 + (k // 5) * px, px, px, col)
def center(s, y, px, col, bg=None):
    text(s, (W - len(s) * 6 * px) // 2, y, px, col, bg)
